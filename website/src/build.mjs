// Builds the generated parts of the website from the repository's own sources, so the site never drifts from the app:
//   - app-ui.css: the app's components (docs/mockups/src/shared.css, ux §3) scaled for the page; one design point is
//     --u, so a drawing of the window fits any width
//   - the hero window in index.html: cards, format picker and action bars, drawn by the mockups' own builders
//     (docs/mockups/src/shared.js and files.js, and the pages target-picker, window-cards, -converting and -done)
//   - the format list and every count in index.html, from docs/specs/data/format-matrix.json
//   - the ?v= content hashes on every asset URL
// With --assets it first re-renders favicon-32.png and apple-touch-icon.png from scripts/make-icon.swift (the app icon's
// own renderer) and og.png from og.html (index.html's hero, 1200 × 630) with headless Google Chrome. icon.svg is drawn
// by hand to the same geometry; when make-icon.swift changes, update icon.svg, then run
//   node website/src/build.mjs --assets
// Needs Node 18+; --assets also needs swift (Command Line Tools) and Google Chrome (CHROME=<path> to use another).
import { readFileSync, writeFileSync, copyFileSync, mkdtempSync, rmSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { createServer } from "node:http";
import { execFileSync, spawn } from "node:child_process";
import { tmpdir } from "node:os";
import { join, extname } from "node:path";
import vm from "node:vm";

const ROOT = new URL("../../", import.meta.url).pathname;
const SITE = join(ROOT, "website");
const MOCK = join(ROOT, "docs/mockups/src");
const read = (p) => readFileSync(p, "utf8");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const fmt = (n) => n.toLocaleString("en-US");

// ---------- the mockups' builders, run as they run in the browser ----------
const sandbox = { location: { hash: "" }, document: { documentElement: { classList: { add() {} } } } };
sandbox.window = sandbox;
vm.createContext(sandbox);
vm.runInContext(read(join(MOCK, "shared.js")) + read(join(MOCK, "files.js")), sandbox);
const { SC, FILES: F } = sandbox;
// Runs a mockup page's script with SC.render captured, and returns what the page would have drawn.
function page(name) {
  const code = read(join(MOCK, name)).match(/<script>\n([\s\S]*?)<\/script>/)[1];
  let drawn;
  sandbox.SC = { ...SC, render: (o) => { drawn = o; } };
  vm.runInContext(`{${code}}`, sandbox);
  sandbox.SC = SC;
  return drawn;
}
const actionbar = (html) => html.slice(html.indexOf('<div class="actionbar">')).replace(/\s+$/, "");

// ---------- scaling: one mockup pixel becomes one --u ----------
const scaleLengths = (s) => s.replace(/(-?\d*\.?\d+)px/g, "calc($1 * var(--u))");
const scaleHTML = (html) => html
  .replace(/style="([^"]*)"/g, (_, s) => `style="${scaleLengths(s)}"`)
  .replace(/<svg width="([\d.]+)" height="([\d.]+)"/g, '<svg style="width:calc($1 * var(--u));height:calc($2 * var(--u))"');
// Gradient and clip ids of the thumbnails repeat from card to card; each copy gets its own.
const ownIds = (html, tag) => html.replace(/id="([^"]+)"/g, `id="$1-${tag}"`).replace(/url\(#([^)]+)\)/g, `url(#$1-${tag})`);

function appCSS() {
  const css = read(join(MOCK, "shared.css")).replace(/\/\*[\s\S]*?\*\//g, "");
  const light = [], dark = [], scoped = [], scopedDark = [], appTokens = [], appTokensDark = [];
  for (const [, sel, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = sel.trim();
    if (selector.startsWith("@font-face") || ["*", "html, body", "body"].includes(selector)) continue;
    if (selector === ":root" || selector === "html.dark") {
      for (const decl of body.split(";").map((d) => d.trim()).filter(Boolean)) {
        if (decl.startsWith("--rounded")) continue;
        const into = decl.includes("px") ? (selector === ":root" ? appTokens : appTokensDark) : (selector === ":root" ? light : dark);
        into.push(scaleLengths(decl));
      }
      continue;
    }
    const isDark = selector.split(",").every((s) => s.trim().startsWith("html.dark "));
    // The category hooks (.c-img, …) only set custom properties, so the rest of the page uses them too.
    const scope = selector.split(",").map((s) => s.trim().replace(/^html\.dark /, "")).map((s) => (s.startsWith(".c-") ? s : ".app " + s)).join(", ");
    (isDark ? scopedDark : scoped).push(`${scope} { ${scaleLengths(body.trim())} }`);
  }
  return `/* Generated by website/src/build.mjs from docs/mockups/src/shared.css (ux §3): the app's tokens and components,
   scaled so that one design point is --u. Don't edit; edit the mockups or the build. */
:root { ${light.join("; ")}; --rounded: ui-rounded, "SF Pro Rounded", system-ui, -apple-system, sans-serif; }
.app { ${appTokens.join("; ")}; }
${scoped.join("\n")}
@media (prefers-color-scheme: dark) {
  :root { ${dark.join("; ")}; }
  .app { ${appTokensDark.join("; ")}; }
${scopedDark.map((r) => "  " + r).join("\n")}
}
`;
}

// ---------- the hero: the window converting eight files (ux §5.3–5.7) ----------
// Each card is drawn twice, ready and done; the page's script runs one into the other (app.js).
const DONE = {
  heic: "1.9 MB · was 4.2 MB", docx: "312 KB · 12 pages", mov: "286 MB · was 1.4 GB", wav: "61 MB · V0 · 41:20",
  xlsx: "96 KB · 3 pages", pptx: "2.1 MB · 18 pages", epub: "1.2 MB · 214 pages", svg: "44 KB · 512 × 512",
};
function hero() {
  const cards = Object.keys(DONE).map((k, i) => {
    const f = F[k];
    const progress = `<div class="progress" style="--from:var(--${f.cat});--to:var(--${f.dstCat})"><i></i></div>`;
    const ready = SC.card(f).replace(f.thumb + "</div>", f.thumb + progress + "</div>");
    const done = SC.card({ ...f, state: "done", meta: DONE[k], name: f.name.replace(/\.\w+$/, "." + f.dst.toLowerCase()) });
    return `<div class="hc" data-k="${k}">${ownIds(ready, `${i}a`)}${ownIds(done, `${i}b`)}</div>`;
  }).join("");
  const ready = actionbar(page("window-cards.html").content);
  const run = actionbar(page("window-converting.html").content)
    .replace("<b>Converting… 2 of 8 done</b>", "<b>Converting… <span data-done>0</span> of 8 done</b>")
    .replace('<div style="width:34%;', '<div data-bar style="width:0%;');
  const done = actionbar(page("window-done.html").content)
    .replace("Done. 7 of 8 files converted", "Done. 8 of 8 files converted")
    .replace("1.7 GB → 356 MB, saved next to the originals · 1 needs a password", "1.7 GB → 353 MB, saved next to the originals");
  const picker = page("target-picker.html").after.replace(/^\s*<div class="popover" style="[^"]*"/, '<div class="popover"');
  const tools = SC.defaultTools();
  const html = `<div class="app" data-app data-phase="ready" aria-hidden="true">
<div class="desk"></div>
<div class="window">
${SC.toolbar({ subtitle: "8 files · 1.7 GB", tools }).replace("<span>8 files · 1.7 GB</span>", '<span data-sub>8 files · 1.7 GB</span>')}
<div class="content"><div class="grid">${cards}</div>
${ready.replace('<div class="actionbar">', '<div class="actionbar ab-ready">')}
${run.replace('<div class="actionbar">', '<div class="actionbar ab-run">')}
${done.replace('<div class="actionbar">', '<div class="actionbar ab-done">')}
</div>
${picker}
</div>
</div>`;
  return scaleHTML(html);
}

// ---------- what it converts: every format in the matrix ----------
const CATS = [
  ["image", "img", "Images"], ["document", "doc", "Documents"], ["video", "vid", "Video"], ["audio", "aud", "Audio"],
  ["spreadsheet", "sht", "Spreadsheets"], ["presentation", "sld", "Slides"], ["ebook", "ebk", "E-books"],
  ["archive", "arc", "Archives"], ["vector", "vec", "Vector"], ["cad", "cad", "CAD"], ["font", "fnt", "Fonts"],
];
const matrix = JSON.parse(read(join(ROOT, "docs/specs/data/format-matrix.json")));
const catOf = Object.fromEntries(matrix.formats.map((f) => [f.input, CATS.find((c) => c[0] === f.category)[1]]));
catOf.sfz ??= "aud"; // SFZ instrument (with its samples) is only ever an output, of SF2 sound banks
const order = Object.fromEntries(CATS.map((c, i) => [c[1], i]));
const offered = (f) => f.outputs.filter((o) => o.need !== "no");
const COUNTS = {
  formats: matrix.formats.length,
  conversions: matrix.formats.reduce((n, f) => n + offered(f).length, 0),
  kinds: CATS.length,
  builtin: matrix.formats.reduce((n, f) => n + offered(f).filter((o) => o.need !== "required").length, 0),
  cloudconvert: matrix.formats.reduce((n, f) => n + offered(f).filter((o) => o.origin === "cloudconvert").length, 0),
  ccTotal: matrix.formats.reduce((n, f) => n + f.outputs.filter((o) => o.origin === "cloudconvert").length, 0),
};
COUNTS.more = COUNTS.conversions - COUNTS.cloudconvert;

function formatList() {
  const groups = CATS.map(([cat, c, title]) => {
    const fs = matrix.formats.filter((f) => f.category === cat).sort((a, b) => a.input.localeCompare(b.input));
    const rows = fs.map((f) => {
      const outs = offered(f).sort((a, b) => order[catOf[a.output]] - order[catOf[b.output]] || a.output.localeCompare(b.output));
      const pills = outs.map((o) => `<b class="c-${catOf[o.output]}${o.need === "required" ? " h" : ""}">${esc(o.output.toUpperCase())}${o.need === "required" ? '<i class="vh"> (helper)</i>' : ""}</b>`).join("");
      return `<li class="fx" data-s="${esc(f.input + " " + f.name.toLowerCase())}"><span class="fx-in c-${c}">${esc(f.input.toUpperCase())}</span><span class="fx-name">${esc(f.name)}</span><span class="fx-out" data-out="${outs.map((o) => o.output).join(" ")}">${pills}</span></li>`;
    }).join("\n");
    return `<section class="fx-g c-${c}" data-cat="${c}" aria-labelledby="fx-${c}"><h3 class="fx-h" id="fx-${c}"><i aria-hidden="true"></i>${title} <span>${fs.length} formats</span></h3>
<ul class="fx-list">
${rows}
</ul></section>`;
  }).join("\n");
  const chips = `<button type="button" class="fx-chip" data-filter="" aria-pressed="true">All <span>${COUNTS.formats}</span></button>` +
    CATS.map(([cat, c, title]) => `<button type="button" class="fx-chip c-${c}" data-filter="${c}" aria-pressed="false"><i aria-hidden="true"></i>${title} <span>${matrix.formats.filter((f) => f.category === cat).length}</span></button>`).join("");
  return { groups, chips };
}

// ---------- index.html ----------
const replaceBlock = (html, name, content) => {
  const re = new RegExp(`(<!-- build:${name} -->)[\\s\\S]*?(<!-- /build:${name} -->)`);
  if (!re.test(html)) throw new Error(`index.html has no build:${name} block`);
  return html.replace(re, `$1\n${content}\n$2`);
};
const hash = (file) => createHash("sha256").update(readFileSync(join(SITE, file))).digest("hex").slice(0, 8);
const ASSETS = ["styles.css", "app-ui.css", "app.js", "icon.svg", "favicon-32.png", "apple-touch-icon.png", "og.png"];

function build() {
  writeFileSync(join(SITE, "app-ui.css"), appCSS());
  const { groups, chips } = formatList();
  let html = read(join(SITE, "index.html"));
  html = replaceBlock(html, "hero", hero());
  html = replaceBlock(html, "chips", chips);
  html = replaceBlock(html, "formats", groups);
  html = html.replace(/(data-n="(\w+)"[^>]*>)[^<]*/g, (_, open, key) => {
    if (!(key in COUNTS)) throw new Error(`no count named ${key}`);
    return open + fmt(COUNTS[key]);
  });
  for (const file of ASSETS) {
    if (!existsSync(join(SITE, file))) continue;
    html = html.replaceAll(new RegExp(`${file.replace(".", "\\.")}\\?v=[0-9a-f]+`, "g"), `${file}?v=${hash(file)}`);
  }
  writeFileSync(join(SITE, "index.html"), html);
  console.log(`index.html: ${COUNTS.formats} formats, ${fmt(COUNTS.conversions)} conversions (${fmt(COUNTS.cloudconvert)} of CloudConvert's ${fmt(COUNTS.ccTotal)} + ${COUNTS.more})`);
}

// ---------- --assets: icons from make-icon.swift, og.png from og.html ----------
const CHROME = process.env.CHROME || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
function chrome(url, out, w, h, extra = []) {
  const profile = mkdtempSync(join(tmpdir(), "sc-site-chrome-"));
  return new Promise((resolve, reject) => {
    const p = spawn(CHROME, ["--headless=new", "--disable-gpu", "--no-first-run", "--no-default-browser-check", "--hide-scrollbars",
      `--user-data-dir=${profile}`, "--force-device-scale-factor=1", `--window-size=${w},${h}`, ...extra, `--screenshot=${out}`, url], { stdio: "ignore" });
    p.on("exit", (code) => { rmSync(profile, { recursive: true, force: true }); code === 0 ? resolve() : reject(new Error(`Chrome exited with ${code} for ${url}`)); });
  });
}
const TYPES = { ".html": "text/html", ".css": "text/css", ".js": "text/javascript", ".svg": "image/svg+xml", ".png": "image/png", ".otf": "font/otf" };
async function assets() {
  const tmp = mkdtempSync(join(tmpdir(), "sc-site-"));
  execFileSync("swift", [join(ROOT, "scripts/make-icon.swift"), tmp], { stdio: "inherit" });
  const iconset = join(tmp, "AppIcon.iconset");
  copyFileSync(join(iconset, "icon_32x32.png"), join(SITE, "favicon-32.png"));
  // Home-screen icons get no transparency: the 1024-point icon on white, at 180.
  writeFileSync(join(tmp, "touch.html"), `<!doctype html><style>html,body{margin:0;background:#fff}img{display:block;width:180px;height:180px}</style><img src="icon_512x512@2x.png">`);
  copyFileSync(join(iconset, "icon_512x512@2x.png"), join(tmp, "icon_512x512@2x.png"));
  await chrome("file://" + join(tmp, "touch.html"), join(SITE, "apple-touch-icon.png"), 180, 180, ["--allow-file-access-from-files"]);
  // og.png: og.html frames index.html, so the folder is served over HTTP for the frame to be readable.
  const server = createServer((req, res) => {
    const path = join(SITE, decodeURIComponent(new URL(req.url, "http://x").pathname));
    if (!path.startsWith(SITE) || !existsSync(path)) { res.writeHead(404).end(); return; }
    res.writeHead(200, { "content-type": TYPES[extname(path)] || "application/octet-stream" }).end(readFileSync(path));
  });
  await new Promise((r) => server.listen(0, "127.0.0.1", r));
  try {
    await chrome(`http://127.0.0.1:${server.address().port}/og.html`, join(SITE, "og.png"), 1200, 630, ["--virtual-time-budget=3200", "--blink-settings=preferredColorScheme=1"]);
  } finally {
    server.close();
    rmSync(tmp, { recursive: true, force: true });
  }
  console.log("Rendered favicon-32.png, apple-touch-icon.png and og.png");
}

build();
if (process.argv.includes("--assets")) { await assets(); build(); }
