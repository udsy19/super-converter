            check(entry.path == "LICENSE", "name \(entry.path)")
            let parts = Calendar(identifier: .gregorian).dateComponents([.year, .month, .day, .hour, .minute, .second], from: entry.modified ?? .distantPast)
            check(parts.year == 2024 && parts.month == 5 && parts.day == 16 && parts.hour == 23 && parts.minute == 8 && parts.second == 26, "date \(parts)")
            check(!tree.wasEncrypted, "not encrypted")
