private func aceWork<T>(_ body: (URL) throws -> T) rethrows -> T {
    let dir = FileManager.default.temporaryDirectory.appendingPathComponent("sc-ace-\(UUID().uuidString)")
    try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: dir) }
    return try body(dir)
}

private func standardCRC(_ data: Data) -> UInt32 { ~ACECRC.crc32([UInt8](data)) }

private final class ACEProgress: @unchecked Sendable {
    private let lock = NSLock()
    private var units: [String] = []
    func add(_ unit: String?) { lock.lock(); if let unit { units.append(unit) }; lock.unlock() }
    var all: [String] { lock.lock(); defer { lock.unlock() }; return units }
}

private var aceCounter = 0

private func aceRequest(_ bytes: Data, in dir: URL, password: String? = nil, nameEncoding: NameEncoding = .auto,
                        progress: ACEProgress? = nil, cancelled: Bool = false) throws -> ArchiveReadRequest {
    aceCounter += 1
    let source = dir.appendingPathComponent("a\(aceCounter).ace")
    try bytes.write(to: source)
    return ArchiveReadRequest(source: source, format: "ace", root: dir.appendingPathComponent("out\(aceCounter)"), password: password,
                              nameEncoding: nameEncoding, report: { progress?.add($0.unit) }, isCancelled: { cancelled })
}

private func aceRead(_ bytes: Data, in dir: URL, password: String? = nil, nameEncoding: NameEncoding = .auto) throws -> ArchiveTree {
    try ACEKit.read(aceRequest(bytes, in: dir, password: password, nameEncoding: nameEncoding))
}

/// The single file of a tree, checked against the fixture's size and checksum.
private func aceCheckSingle(_ fixture: ACEFixture, _ label: String, password: String? = nil) {
    aceWork { dir in
        do {
            let tree = try aceRead(fixture.data, in: dir, password: password)
            let files = tree.entries.filter { $0.kind == .file }
            check(files.count == 1, "\(label): one file, got \(files.count)")
            guard let file = files.first, let url = file.extracted, let content = try? Data(contentsOf: url) else {
                check(false, "\(label): no extracted file"); return
            }
            check(content.count == fixture.size && file.size == Int64(fixture.size), "\(label): size \(content.count) vs \(fixture.size)")
            check(standardCRC(content) == fixture.crc, "\(label): checksum")
        } catch {
            check(false, "\(label): threw \(error)")
        }
    }
}

private func aceThrows(_ bytes: Data, _ expected: ArchiveError, _ label: String, password: String? = nil) {
    aceWork { dir in
        do {
            _ = try aceRead(bytes, in: dir, password: password)
            check(false, "\(label): expected \(expected)")
        } catch let error as ArchiveError {
            check(error == expected, "\(label): expected \(expected), got \(error)")
        } catch {
            check(false, "\(label): unexpected \(error)")
        }
    }
}

/// A small deterministic generator for the mutation tests.
private struct ACEGenerator {
    var state: UInt64
    mutating func next(_ bound: Int) -> Int {
        state ^= state << 13; state ^= state >> 7; state ^= state << 17
        return Int(state % UInt64(bound))
    }
}

/// Every mutation must either extract or throw; a trap would end the whole run.
private func aceMutations(_ original: Data, label: String, count: Int, seed: UInt64) {
    var generator = ACEGenerator(state: seed | 1)
    var thrown = 0
    aceWork { dir in
        for round in 0..<count {
            var bytes = original
            switch round % 5 {
            case 0: bytes[generator.next(bytes.count)] ^= UInt8(1 << generator.next(8))
            case 1: bytes[generator.next(bytes.count)] = UInt8(generator.next(256))
            case 2: bytes = bytes.prefix(generator.next(bytes.count))
            case 3:
                // Garble the packed data (after the first two headers) and keep the headers valid.
                if bytes.count > 80 { bytes[60 + generator.next(bytes.count - 60)] ^= UInt8(1 << generator.next(8)) }
            default:
                // Change a byte inside the file header and fix the header checksum, so the parser trusts it.
                let mainSize = bytes.count > 4 ? Int(bytes[2]) | Int(bytes[3]) << 8 : 0
                let start = 4 + mainSize
                guard bytes.count > start + 8 else { continue }
                let size = Int(bytes[start + 2]) | Int(bytes[start + 3]) << 8
                guard size > 4, bytes.count >= start + 4 + size else { continue }
                bytes[start + 4 + generator.next(size)] = UInt8(generator.next(256))
                let crc = ACECRC.crc16(Array(bytes[(start + 4)..<(start + 4 + size)]))
                bytes[start] = UInt8(crc & 0xFF); bytes[start + 1] = UInt8(crc >> 8)
            }
            do { _ = try aceRead(bytes, in: dir) } catch is ArchiveError { thrown += 1 } catch { check(false, "\(label): non-archive error \(error)") }
            try? FileManager.default.removeItem(at: dir.appendingPathComponent("out\(aceCounter)"))
        }
    }
    check(thrown > count / 4, "\(label): mutations are mostly rejected (\(thrown) of \(count))")
}

func registerArchiveKitACETests() {
    SelfTest.cases.append(("ArchiveKit.ace.crc", {
        check(ACECRC.crc32(Array("123456789".utf8)) == 873_187_033, "ACE CRC-32 of 123456789")
