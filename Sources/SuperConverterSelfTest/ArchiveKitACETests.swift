        bf.decrypt(&first)
        check(first == [0xb7, 0x77, 0x46, 0x40, 0x35, 0x2e, 0x65, 0x72], "first block \(first)")
        var second = [UInt8](repeating: 0xC7, count: 8)
        bf.decrypt(&second)
        check(second == [0x65, 0x45, 0x05, 0xc4, 0xa5, 0x85, 0x29, 0xbc], "second block \(second)")
    }))

    SelfTest.cases.append(("ArchiveKit.ace.lz77-v1", {
        aceCheckSingle(ACEFixtures.license1, "license1")
